-- 1. CATALOG CONTEXT
-- =====================================================================

CREATE TABLE catalog.brand (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    logo_url VARCHAR(512),
    is_visible BOOLEAN NOT NULL DEFAULT false
);

CREATE TABLE catalog.category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id BIGINT,
    name VARCHAR(100) NOT NULL,
    depth SMALLINT NOT NULL DEFAULT 0,
    product_count INTEGER NOT NULL DEFAULT 0,
    is_in_navigation BOOLEAN NOT NULL DEFAULT false,
    is_visible BOOLEAN NOT NULL DEFAULT false,
    icon_url VARCHAR(512),
    CONSTRAINT fk_category_parent FOREIGN KEY (parent_id) REFERENCES catalog.category(id) ON DELETE SET NULL
);
CREATE INDEX idx_category_parent_id ON catalog.category(parent_id);

CREATE TABLE catalog.product_type (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE catalog.attribute_definition (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_type_id BIGINT,
    name VARCHAR(100) NOT NULL,
    selection_mode SMALLINT NOT NULL DEFAULT 0,
    input_mode SMALLINT NOT NULL DEFAULT 0,
    allowed_values TEXT,
    kind SMALLINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_attr_def_product_type FOREIGN KEY (product_type_id) REFERENCES catalog.product_type(id) ON DELETE CASCADE
);
CREATE INDEX idx_attr_def_product_type_id ON catalog.attribute_definition(product_type_id);

CREATE TABLE catalog.product (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id BIGINT,
    category_id BIGINT NOT NULL,
    product_type_id BIGINT,
    name VARCHAR(200) NOT NULL,
    primary_image_url VARCHAR(512),
    product_code VARCHAR(64) NOT NULL UNIQUE,
    deleted_at TIMESTAMPTZ,
    is_published BOOLEAN NOT NULL DEFAULT false,
    is_new_arrival BOOLEAN NOT NULL DEFAULT false,
    is_featured BOOLEAN NOT NULL DEFAULT false,
    approval_status SMALLINT NOT NULL DEFAULT 0,
    units_sold INTEGER NOT NULL DEFAULT 0 CHECK (units_sold >= 0),
    search_keywords TEXT,
    promotion_type SMALLINT NOT NULL DEFAULT 0,
    description TEXT,
    version INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_product_brand FOREIGN KEY (brand_id) REFERENCES catalog.brand(id) ON DELETE SET NULL,
    CONSTRAINT fk_product_category FOREIGN KEY (category_id) REFERENCES catalog.category(id) ON DELETE RESTRICT,
    CONSTRAINT fk_product_type FOREIGN KEY (product_type_id) REFERENCES catalog.product_type(id) ON DELETE SET NULL
);
CREATE INDEX idx_product_brand_id ON catalog.product(brand_id);
CREATE INDEX idx_product_category_id ON catalog.product(category_id);
CREATE INDEX idx_product_type_id ON catalog.product(product_type_id);
CREATE INDEX idx_product_deleted_at ON catalog.product(deleted_at) WHERE deleted_at IS NULL;

CREATE TABLE catalog.product_media (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    media_type VARCHAR(50),
    url VARCHAR(512) NOT NULL,
    display_order INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_product_media_product FOREIGN KEY (product_id) REFERENCES catalog.product(id) ON DELETE CASCADE
);
CREATE INDEX idx_product_media_product_id ON catalog.product_media(product_id);

CREATE TABLE catalog.product_sku (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    sku_code VARCHAR(64) NOT NULL UNIQUE,
    list_price NUMERIC(12,2) NOT NULL DEFAULT 0.00 CHECK (list_price >= 0),
    sale_price NUMERIC(12,2) CHECK (sale_price >= 0),
    on_hand_qty INTEGER NOT NULL DEFAULT 0 CHECK (on_hand_qty >= 0),
    reserved_qty INTEGER NOT NULL DEFAULT 0 CHECK (reserved_qty >= 0),
    low_stock_threshold INTEGER NOT NULL DEFAULT 5 CHECK (low_stock_threshold >= 0),
    image_url VARCHAR(512),
    units_sold INTEGER NOT NULL DEFAULT 0 CHECK (units_sold >= 0),
    sku_attributes JSONB,
    version INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_product_sku_product FOREIGN KEY (product_id) REFERENCES catalog.product(id) ON DELETE CASCADE,
    CONSTRAINT ck_product_sku_stock CHECK (reserved_qty <= on_hand_qty)
);
CREATE INDEX idx_product_sku_product_id ON catalog.product_sku(product_id);

CREATE TABLE catalog.product_attribute_value (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    attribute_id BIGINT NOT NULL,
    value TEXT,
    CONSTRAINT fk_attr_val_product FOREIGN KEY (product_id) REFERENCES catalog.product(id) ON DELETE CASCADE,
    CONSTRAINT fk_attr_val_attr FOREIGN KEY (attribute_id) REFERENCES catalog.attribute_definition(id) ON DELETE CASCADE
);
CREATE INDEX idx_attr_val_product_id ON catalog.product_attribute_value(product_id);
CREATE INDEX idx_attr_val_attribute_id ON catalog.product_attribute_value(attribute_id);

CREATE TABLE catalog.category_attribute (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL,
    attribute_id BIGINT NOT NULL,
    CONSTRAINT fk_cat_attr_category FOREIGN KEY (category_id) REFERENCES catalog.category(id) ON DELETE CASCADE,
    CONSTRAINT fk_cat_attr_attribute FOREIGN KEY (attribute_id) REFERENCES catalog.attribute_definition(id) ON DELETE CASCADE,
    CONSTRAINT uq_cat_attr UNIQUE (category_id, attribute_id)
);
CREATE INDEX idx_cat_attr_category_id ON catalog.category_attribute(category_id);
CREATE INDEX idx_cat_attr_attribute_id ON catalog.category_attribute(attribute_id);

CREATE TABLE catalog.product_approval_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewer_admin_id VARCHAR(64),
    decision SMALLINT NOT NULL DEFAULT 0,
    comment TEXT,
    CONSTRAINT fk_approval_product FOREIGN KEY (product_id) REFERENCES catalog.product(id) ON DELETE CASCADE
);
CREATE INDEX idx_approval_product_id ON catalog.product_approval_event(product_id);

CREATE TABLE catalog.product_price_change (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    old_list_price NUMERIC(12,2),
    new_list_price NUMERIC(12,2),
    old_sale_price NUMERIC(12,2),
    new_sale_price NUMERIC(12,2),
    changed_by_admin_id VARCHAR(64),
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_price_change_product FOREIGN KEY (product_id) REFERENCES catalog.product(id) ON DELETE CASCADE
);
CREATE INDEX idx_price_change_product_id ON catalog.product_price_change(product_id);

