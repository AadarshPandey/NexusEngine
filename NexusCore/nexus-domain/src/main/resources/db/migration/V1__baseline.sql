CREATE TABLE ordering.order_policy (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flash_payment_timeout_min INTEGER NOT NULL DEFAULT 60 CHECK (flash_payment_timeout_min > 0),
    payment_timeout_min INTEGER NOT NULL DEFAULT 120 CHECK (payment_timeout_min > 0),
    auto_confirm_receipt_days INTEGER NOT NULL DEFAULT 15 CHECK (auto_confirm_receipt_days >= 0),
    auto_complete_days INTEGER NOT NULL DEFAULT 7 CHECK (auto_complete_days >= 0),
    review_window_days INTEGER NOT NULL DEFAULT 7 CHECK (review_window_days >= 0),
    CONSTRAINT ck_order_policy_singleton CHECK (id = 1)
);

CREATE TABLE ordering.merchant_address (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label VARCHAR(100),
    is_default_ship_from BOOLEAN NOT NULL DEFAULT false,
    is_default_return_to BOOLEAN NOT NULL DEFAULT false,
    contact_name VARCHAR(100),
    contact_phone VARCHAR(32),
    state VARCHAR(100),
    city VARCHAR(100),
    address_line VARCHAR(500)
);

CREATE TABLE ordering.return_reason (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label VARCHAR(100) NOT NULL UNIQUE,
    display_order INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

