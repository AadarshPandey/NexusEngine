    grand_total_amount NUMERIC(12,2) NOT NULL DEFAULT 0.00 CHECK (grand_total_amount >= 0),
    shipping_amount NUMERIC(12,2) NOT NULL DEFAULT 0.00 CHECK (shipping_amount >= 0),
    promotion_discount_amount NUMERIC(12,2) NOT NULL DEFAULT 0.00 CHECK (promotion_discount_amount >= 0),
