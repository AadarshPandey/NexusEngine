import org.springframework.web.bind.annotation.*;

import java.util.List;


/**
 * Represents the CartController component.
 * Provides core functionality and operations for CartController.
 */
@RestController
@Tag(name = "CartController", description = "Oms cart item controller APIs")
@RequestMapping("/portal/cart")
@RequiredArgsConstructor
public class CartController {
    private final CartService cartItemService;
    private final MemberService memberService;

    @Operation(summary = "Add Operation")
    @PostMapping("/add")

    public CommonResult add(@RequestBody CartItem cartItem) {
        int count = cartItemService.add(cartItem);
        if (count > 0) {
            return CommonResult.success(count);
        }
        return CommonResult.failed();
    }

    @Operation(summary = "List Operation")
    @GetMapping("/list")

    public CommonResult<List<CartItem>> list() {
        List<CartItem> cartItemList = cartItemService.list(memberService.getCurrentMember().getId());
        return CommonResult.success(cartItemList);
    }

    @Operation(summary = "List promotion Operation")
    @GetMapping("/list/promotion")

    public CommonResult<List<CartPromotionItem>> listPromotion(@RequestParam(required = false) List<Long> cartIds) {
        List<CartPromotionItem> cartPromotionItemList = cartItemService.listPromotion(memberService.getCurrentMember().getId(), cartIds);
        return CommonResult.success(cartPromotionItemList);
    }

    @Operation(summary = "Update quantity Operation")
    @GetMapping("/update/quantity")

    public CommonResult updateQuantity(@RequestParam("id") Long id,
                                       @RequestParam("quantity") Integer quantity) {
        int count = cartItemService.updateQuantity(id, memberService.getCurrentMember().getId(), quantity);
        if (count > 0) {
            return CommonResult.success(count);
        }
        return CommonResult.failed();
    }

    @Operation(summary = "Get cart product Operation")
    @GetMapping("/getProduct/{productId}")

    public CommonResult<CartProduct> getCartProduct(@PathVariable("productId") Long productId) {
        CartProduct cartProduct = cartItemService.getCartProduct(productId);
        return CommonResult.success(cartProduct);
    }

    @Operation(summary = "Update attr Operation")
    @PostMapping("/update/attr")

    public CommonResult updateAttr(@RequestBody CartItem cartItem) {
        int count = cartItemService.updateAttr(cartItem);
        if (count > 0) {
            return CommonResult.success(count);
        }
        return CommonResult.failed();
    }

    @Operation(summary = "Delete Operation")
    @PostMapping("/delete")

    public CommonResult delete(@RequestParam("ids") List<Long> ids) {
        int count = cartItemService.delete(memberService.getCurrentMember().getId(), ids);
        if (count > 0) {
            return CommonResult.success(count);
        }
        return CommonResult.failed();
    }

    @Operation(summary = "Clear Operation")
    @PostMapping("/clear")

    public CommonResult clear() {
        int count = cartItemService.clear(memberService.getCurrentMember().getId());
        if (count > 0) {
            return CommonResult.success(count);
        }
        return CommonResult.failed();
    }
}
